// Node 24: keep server and packaged HA readers on the mobile implementation.
const fs=require('node:fs'),path=require('node:path');
const {stripTypeScriptTypes}=require('node:module');
const root=path.resolve(__dirname,'..');
const source=stripTypeScriptTypes(fs.readFileSync(path.join(root,'mobile/speechFocus.ts'),'utf8'));
const detector=source.slice(0,source.indexOf('export function speechFocusBrowserSource'))
  .replace(/^import .*speechFocus.generated.*\n/m,'')
  .replace('export function detectBubbleRegion','function detectBubbleRegion')
  .split('\n').map(line=>line.trimEnd()).join('\n').trimStart();
const output='// Generated by scripts/sync-speech-focus.cjs; edit mobile/speechFocus.ts.\n'+detector+
  '\nexport function createSpeechFocusController(){return installSpeechFocus(detectBubbleRegion);}\n';
for(const file of ['web/speech-focus.js','archivist/app/web/speech-focus.js']){
  const target=path.join(root,file);
  if(process.argv.includes('--check')){
    if(fs.readFileSync(target,'utf8')!==output)throw Error('Speech focus drift: '+file);
  }else fs.writeFileSync(target,output);
}

const mobileOutput='// Generated by scripts/sync-speech-focus.cjs. Do not use Function.toString in Hermes.\nexport const speechFocusSource='+JSON.stringify('(function(){'+detector+'\nwindow.__archivistSpeechFocus=installSpeechFocus(detectBubbleRegion);})();')+';\n';
const mobileTarget=path.join(root,'mobile/speechFocus.generated.ts');
if(process.argv.includes('--check')){if(fs.readFileSync(mobileTarget,'utf8')!==mobileOutput)throw Error('Mobile speech focus drift');}
else fs.writeFileSync(mobileTarget,mobileOutput);
