const assert=require('node:assert/strict'),fs=require('node:fs');
const text=fs.readFileSync(__dirname+'/App.tsx','utf8');
const start=text.indexOf('function CelebrationOverlay('),end=text.indexOf('function DismissSheetHandle(');
assert.ok(start>=0&&end>start,'overlay exists');
const source=text.slice(start,end);
assert.match(source,/Animated\.timing\(sparks,\{toValue:1,duration:950,useNativeDriver:true\}\)\.start\(\)/,'reward particles need actual animation driver');
assert.ok(source.includes('sparks.setValue(0)'), 'clear previous animation on repeat');
assert.match(source,/Animated\.delay\(reduceMotion\?3000:2080\)/,'milestone remains visibly present near 3 seconds');
assert.ok(source.includes('if(!reduceMotion)'), 'decorative particles gated by reduced motion');
console.log('Celebration particle and duration contract passed');
